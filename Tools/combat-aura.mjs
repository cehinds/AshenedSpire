#!/usr/bin/env node
// The aura of the player's combat figure (P-4, docs/DECISIONS.md D-1540..): the data of the web's silhouette glow, src/ui/combatAura.js over content/config/ui/presentation/combatAura.json.
//
//   node Tools/combat-aura.mjs            writes Unity/Assets/StreamingAssets/Content/ui/combatAura.json
//   node Tools/combat-aura.mjs --check    fails when the committed file differs from what the web sources give
//
// The web strokes the figure's silhouette with `drop-shadow(...)` filters (auraFilter): a hard copy of the alpha one pixel to each side and a blurred one below, in the colour of the resource a
// card paid (stamina, mana, hit points), the guard's pale blue while the figure is braced, and the power glow of a spell. This writes the numbers and colours it chooses between; the Unity
// figure draws the glow as a soft silhouette sprite tinted with them (docs/DECISIONS.md D-1540..: UI Toolkit has no filters).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { WEB } from './oracle-core2.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'Unity', 'Assets', 'StreamingAssets', 'Content', 'ui', 'combatAura.json');
const CHECK = process.argv.includes('--check');
const load = (rel) => import(pathToFileURL(join(WEB, rel)).href);
const read = (rel) => readFileSync(join(WEB, rel), 'utf8');

const config = JSON.parse(read('content/config/ui/presentation/combatAura.json'));
const vars = config.vars || {};
const value = (v) => (typeof v === 'string' && v.startsWith('$') ? vars[v.slice(1)] : v);
const frames = Object.fromEntries(Object.entries(config.components.powerFrames).map(([name, f]) => [name, { radius: f.radius, blur: value(f.blur), alpha: f.alpha, brightness: f.brightness }]));
const sizing = config.sizing;
const glow = (g) => ({ radius: g.radius, alpha: g.alpha, blur: value(g.blur) });
const colors = Object.fromEntries(Object.entries(config.components.colors).map(([name, rgb]) => [name, rgb.split(',').map(Number)]));

// The literals the stage keeps inline, read from its source so a change of them fails the check.
const stage = read('src/ui/alternativeCardStage.js');
const spell = /action === 'spell' \? '(\w+)' : frame/.exec(stage);
const guardRests = /\['defend','counter'\]\.includes\(rest\) \? '(\w+)' : rest/.exec(stage);
if (!spell || !guardRests) throw new Error('combat-aura: the stage\'s aura call is not in alternativeCardStage.js');
const aura = read('src/ui/combatAura.js');
if (!/drop-shadow\(\$\{r\}px 0 0 \$\{color\}\)/.test(aura) || !/drop-shadow\(\$\{-r\}px 0 0 \$\{color\}\)/.test(aura) || !/drop-shadow\(0 \$\{r\}px \$\{blur\}px \$\{color\}\)/.test(aura)) {
  throw new Error('combat-aura: the three shadows of an aura are not what this tool reads');
}
const web = await load('src/ui/combatAura.js');
if (JSON.stringify(web.POWER_FRAMES) !== JSON.stringify(frames)) throw new Error('combat-aura: POWER_FRAMES differs from the config file');

const built = {
  comment: 'Generated by Tools/combat-aura.mjs from the web (ui/combatAura.js, content/config/ui/presentation/combatAura.json, ui/alternativeCardStage.js). Do not edit. The silhouette glow of the player figure: the colour of each resource (rgb), the power frames, the three glow strengths and the pose the stage names for a spell.',
  colors,
  powerFrames: frames,
  guardedRestPoses: config.behavior.guardedRestPoses,
  defaultPalette: config.behavior.defaultPalette,
  guardedPalette: config.behavior.guardedPalette,
  spread: sizing.spread,
  faded: glow(sizing.faded),
  lit: glow(sizing.lit),
  spellFrame: spell[1],
  guardRest: guardRests[1],
  resting: { innerBlurPx: sizing.restingGlow.innerBlurPx, outerBlurPx: sizing.restingGlow.outerBlurPx, innerAlphaHex: sizing.restingGlow.innerAlphaHex, outerAlphaHex: sizing.restingGlow.outerAlphaHex },
};
const text = `${JSON.stringify(built, null, 1)}\n`;
if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('combat-aura: ui/combatAura.json differs from the web (run node Tools/combat-aura.mjs)'); process.exit(1); }
  console.log(`combat-aura: ok (${Object.keys(colors).length} colours, ${Object.keys(frames).length} power frames)`);
} else {
  writeFileSync(OUT, text);
  console.log(`combat-aura: ${Object.keys(colors).length} colours, ${Object.keys(frames).length} power frames`);
}
