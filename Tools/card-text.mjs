const list = (name, source = faceText) => {
  const m = source.match(new RegExp(`const ${name} = \\[([^\\]]*)\\]`));
  if (!m) throw new Error(`card-text: ${name} not found`);
  return [...m[1].matchAll(/'([^']*)'/g)].map((x) => x[1]);
};

// A JS regex literal and its replacement string, in the order a chain of .replace calls applies them.
function replaceChain(source, from) {
  const out = [];
  let i = source.indexOf(from);
  const end = source.indexOf('\n}', i);
  const body = source.slice(i, end > 0 ? end : undefined);
  for (let at = body.indexOf('.replace(/'); at >= 0; at = body.indexOf('.replace(/', at + 1)) {
    let p = at + '.replace('.length + 1, inClass = false;
    for (; p < body.length; p++) {
      const ch = body[p];
      if (ch === '\\') { p++; continue; }
      if (ch === '[') inClass = true;
      else if (ch === ']') inClass = false;
      else if (ch === '/' && !inClass) break;
    }
    const pattern = body.slice(at + '.replace('.length + 1, p);
    let q = p + 1;
    while (/[a-z]/.test(body[q])) q++;
    const flags = body.slice(p + 1, q);
    const rest = body.slice(q).match(/^,\s*'((?:\\.|[^'\\])*)'\s*\)/);
    if (!rest) throw new Error(`card-text: no replacement after /${pattern}/`);
    out.push({ pattern, flags, replacement: new Function(`return '${rest[1]}'`)() });
  }
  return out;
}

