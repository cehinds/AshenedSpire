#!/usr/bin/env node
// The visible ink of the combat figures' frames (P-4, docs/DECISIONS.md D-1540..): the web draws each figure's floor shadow as wide as the opaque pixels of the frame on show
// (src/ui/components/battlefieldStage.js syncFloorShadows over combatSpriteGeometry.js currentSpriteArtBounds / imageBounds: alpha >= 40, found from the edges in).
// This writes, per frame of the enemies' expansion stage (exp.*), of the player's card stage (alt.*, sweep.*, hurt.*) and of the fallen (defeated.*), the first and last opaque column and the
// image's width into ui/figureInk.json, from the imported images (the registry's unityPath).
//
//   node Tools/figure-ink.mjs            writes Unity/Assets/StreamingAssets/Content/ui/figureInk.json (needs the imported art and sharp: ASHEN_SHARP, see Tools/lib/release-art.mjs)
//   node Tools/figure-ink.mjs --check    fails when a frame's source changed since it was measured (the registry's sha256 against the recorded one), without needing the art
//
// A frame already measured whose source is unchanged keeps its numbers, so a machine without the whole art can still refresh the rest.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = join(ROOT, 'Unity', 'Assets', 'StreamingAssets', 'Content');
const OUT = join(CONTENT, 'ui', 'figureInk.json');
const CHECK = process.argv.includes('--check');
const ALPHA = 40;
const registry = JSON.parse(readFileSync(join(CONTENT, 'assets', 'registry.json'), 'utf8'));
const previous = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')).frames : {};
const ids = Object.keys(registry).filter((id) => /^(exp|alt|sweep|hurt|defeated)\./.test(id) && registry[id].unityPath).sort();
const sha = (id) => registry[id].sha256.slice(0, 12);

const frames = {};
let measured = 0, kept = 0;
let sharp = null;
for (const id of ids) {
  const old = previous[id];
  if (old && old.sha === sha(id)) { frames[id] = old; kept++; continue; }
  if (CHECK) { console.error(`figure-ink: ${id} is new or changed since it was measured (run node Tools/figure-ink.mjs)`); process.exit(1); }
  if (!sharp) {
    for (const base of [process.env.ASHEN_SHARP, join(ROOT, 'Tools', 'package.json')].filter(Boolean)) {
      try { sharp = createRequire(base.endsWith('.json') ? base : join(base, 'x.js'))('sharp'); break; } catch { /* next */ }
    }
    if (!sharp) { console.error('figure-ink: the sharp package is needed (cd Tools && npm install, or set ASHEN_SHARP)'); process.exit(1); }
  }
  const file = join(ROOT, 'Unity', registry[id].unityPath);
  if (!existsSync(file)) { console.error(`figure-ink: ${id} is not imported (${registry[id].unityPath})`); process.exit(1); }
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h, channels } = info;
  const opaque = (x, y) => data[(y * w + x) * channels + channels - 1] >= ALPHA;
  const rowHit = (y) => { for (let x = 0; x < w; x++) if (opaque(x, y)) return true; return false; };
  let y0 = 0; while (y0 < h && !rowHit(y0)) y0++;
  let box = null;
  if (y0 < h) {
    let y1 = h - 1; while (y1 > y0 && !rowHit(y1)) y1--;
    const colHit = (x) => { for (let y = y0; y <= y1; y++) if (opaque(x, y)) return true; return false; };
    let x0 = 0; while (!colHit(x0)) x0++;
    let x1 = w - 1; while (x1 > x0 && !colHit(x1)) x1--;
    box = { x0, x1: x1 + 1 };
  }
  frames[id] = { sha: sha(id), width: w, ...(box || { x0: 0, x1: w }) };
  measured++;
}
for (const id of Object.keys(previous)) if (!frames[id] && CHECK) { console.error(`figure-ink: ${id} is no longer a frame`); process.exit(1); }
const text = `${JSON.stringify({ comment: 'Generated by Tools/figure-ink.mjs. Do not edit. The first and one past the last opaque column (alpha >= 40, the web\'s imageBounds) of each combat figure frame and the image\'s width, by registry id; sha is the registry sha256 of the source frame it was measured from.', alpha: ALPHA, frames }, null, 1)}\n`;
if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('figure-ink: ui/figureInk.json differs (run node Tools/figure-ink.mjs)'); process.exit(1); }
  console.log(`figure-ink: ok (${ids.length} frames)`);
} else {
  writeFileSync(OUT, text);
  console.log(`figure-ink: ${ids.length} frames (${measured} measured, ${kept} kept) ${text.length} bytes`);
}
