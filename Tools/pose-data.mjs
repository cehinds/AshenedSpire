#!/usr/bin/env node
// Player pose data (P-1, docs/DECISIONS.md D-1320..): the registration geometry of the player figure's pose frames and the motion constants of the web's pose stage.
//
//   node Tools/pose-data.mjs            writes Unity/Assets/StreamingAssets/Content/ui/poses.json
//   node Tools/pose-data.mjs --check    fails when the committed file differs from what the web sources give
//
// Sources, all at the sha pinned in Tools/export/sources.json (core2.webSha): src/content/poseSprites.js (the canvas, the strip, the tints and one row per shipped frame
// `class_pose_tint` with the crop's place on the shared canvas, the pelvis and the floor line), src/ui/services/PoseAnimator.js (the swing rotation) and
// content/config/ui/presentation/poseAnimator.json (how long a pose is held). The frames themselves are art: ids `pose.<class>.<pose>.<tint>` of assets/registry.json.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, fallback) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : fallback; };
const WEB = arg('--source', process.env.ASHEN_SOURCE || '/home/user/cehinds/ashenspire');
const OUT = join(ROOT, 'Unity', 'Assets', 'StreamingAssets', 'Content', 'ui', 'poses.json');
const CHECK = process.argv.includes('--check');

const sprites = await import(pathToFileURL(join(WEB, 'src/content/poseSprites.js')).href);
const motion = JSON.parse(readFileSync(join(WEB, 'content/config/ui/presentation/poseAnimator.json'), 'utf8'));
const animator = readFileSync(join(WEB, 'src/ui/services/PoseAnimator.js'), 'utf8');
const sequence = /const ATTACK_SEQUENCE = (\[[^\]]*\])/.exec(animator);
if (!sequence) throw new Error('pose-data: ATTACK_SEQUENCE not found in PoseAnimator.js');

// A frame is [x, y, w, h, rx, ry, g]: the crop's place on the canvas, its size, the pelvis and the floor line (poseSprites.js).
const frames = {};
for (const [key, row] of [...sprites.POSE_FRAMES.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) frames[key] = [row.x, row.y, row.w, row.h, row.rx, row.ry, row.g];

const built = {
  comment: 'Generated by Tools/pose-data.mjs from the web at core2.webSha (src/content/poseSprites.js, src/ui/services/PoseAnimator.js, content/config/ui/presentation/poseAnimator.json). Do not edit. '
    + 'The player figure is a pose stage (the web style "animated"): a canvas of canvas.width x canvas.height holds every frame of a class and tint at its own crop (x, y, w, h); the stage seats the idle frame\'s floor line g on the bottom of the figure box and its pelvis rx on the box centre. '
    + 'frames["<class>_<pose>_<tint>"] = [x, y, w, h, rx, ry, g].',
  canvas: { width: sprites.POSE_CANVAS.width, height: sprites.POSE_CANVAS.height },
  strip: sprites.POSE_STRIP,
  tints: sprites.POSE_TINTS,
  attackSequence: JSON.parse(sequence[1].replace(/'/g, '"')),
  motion: { defaultPlayMs: motion.motion.defaultPlayMs, minimumPlayMs: motion.motion.minimumPlayMs },
  frames,
};
const text = `${JSON.stringify(built, null, 1)}\n`;
if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('pose-data: ui/poses.json differs from the web sources (run node Tools/pose-data.mjs)'); process.exit(1); }
  console.log(`pose-data: ok (${Object.keys(frames).length} frames)`);
} else {
  writeFileSync(OUT, text);
  console.log(`pose-data: ui/poses.json ${text.length} bytes, ${Object.keys(frames).length} frames`);
}
