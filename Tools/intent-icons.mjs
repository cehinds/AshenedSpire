if (CHECK) {
  let problems = 0;
  if (!existsSync(JSON_OUT) || readFileSync(JSON_OUT, 'utf8') !== text) { console.error('intent-icons: ui/intentIcons.json differs from the web (run node Tools/intent-icons.mjs)'); problems++; }
  for (const id of Object.keys(icons)) {
    const file = join(IMAGES, `${id}.png`);
    // The images are not committed (they are drawn from the geometry by this tool, like the art import): one that is present must be the current size.
    if (existsSync(file) && readFileSync(file).readUInt32BE(16) !== SIZE) { console.error(`intent-icons: ${id}.png is stale`); problems++; }
    if (!existsSync(`${file}.meta`) || readFileSync(`${file}.meta`, 'utf8') !== metaText(id)) { console.error(`intent-icons: ${id}.png.meta is missing or stale`); problems++; }
  }
  if (problems) process.exit(1);
  console.log(`intent-icons: ok (${Object.keys(icons).length} glyphs)`);
} else {
  let sharp = null;
  for (const base of [process.env.ASHEN_SHARP, join(ROOT, 'Tools', 'package.json')].filter(Boolean)) {
    try { sharp = createRequire(base.endsWith('.json') ? base : join(base, 'x.js'))('sharp'); break; } catch { /* next */ }
  }
  if (!sharp) { console.error('intent-icons: the sharp package is needed (cd Tools && npm install, or set ASHEN_SHARP)'); process.exit(1); }
  writeFileSync(JSON_OUT, text);
  mkdirSync(IMAGES, { recursive: true });
  for (const [id, icon] of Object.entries(icons)) {
    await sharp(Buffer.from(svgOf(icon))).png({ compressionLevel: 9 }).toFile(join(IMAGES, `${id}.png`));
    writeFileSync(join(IMAGES, `${id}.png.meta`), metaText(id));
  }
  console.log(`intent-icons: ${Object.keys(icons).length} glyphs, ${text.length} bytes of geometry`);
}
