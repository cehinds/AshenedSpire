#!/usr/bin/env node
// Writes Content/settings/webKeyMap.json: how a web-format config key maps onto this build's content (US-15.4, D-162).
// Since WP-21 (D-1701) only the player's settings.<key> are imported: the web's gameConfig.* keys tune the 405 tables,
// which a Core 2 run never reads (a configured web run skips the Advanced overlay too), so the map has no roots and
// every gameConfig key is reported, never dropped. The importer in the game still reads data, never a hand-kept list.
//
//   node Tools/web-key-map.mjs           write
//   node Tools/web-key-map.mjs --check   fail on drift
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'Unity', 'Assets', 'StreamingAssets', 'Content', 'settings', 'webKeyMap.json');

const doc = {
  comment: 'Generated by Tools/web-key-map.mjs (D-162, D-1701): web config keys → content. Only settings.<player setting> is imported; settings.gameConfig.* mirrors gameConfig.* and is not imported twice. gameConfig.* has no roots since the 405 tables left the run (WP-21), so every such key is reported, never dropped.',
  gameConfigPrefix: 'gameConfig.',
  settingsPrefix: 'settings.',
  mirrorPrefix: 'settings.gameConfig.',
  renames: [],
  roots: [],
};
const text = `${JSON.stringify(doc, null, 2)}\n`;
if (process.argv.includes('--check')) {
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (now !== text) { console.error('web-key-map: settings/webKeyMap.json is stale; run node Tools/web-key-map.mjs'); process.exit(1); }
  console.log('web-key-map: check ok (settings only)');
} else {
  writeFileSync(OUT, text);
  console.log('web-key-map: wrote the settings-only map');
}
